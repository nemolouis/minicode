#!/usr/bin/env python3
"""Write results/README.md: one row per committed result directory (config, model, split, runs, pass rate, steps), so that a
directory name can be traced to the experiment it belongs to. Re-run after adding results: `python scripts/index_results.py`."""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"


def row(d: Path) -> dict | None:
    try:
        meta = json.loads((d / "meta.json").read_text())
        summ = json.loads((d / "summary.json").read_text())
    except (OSError, ValueError):
        return None
    cfg = meta.get("config", {})
    ci = summ.get("pass_rate_ci95") or [None, None]
    return {
        "dir": d.name, "date": str(meta.get("date", ""))[:10], "config": cfg.get("name", "?"), "model": cfg.get("model", "?"),
        "split": meta.get("split", "?"), "tasks": summ.get("n_tasks"), "runs": summ.get("n_runs"),
        "api_excluded": summ.get("n_api_error_excluded") or 0, "pass": summ.get("pass_rate"), "lo": ci[0], "hi": ci[1],
        "steps": summ.get("mean_steps"), "git": ((meta.get("provenance") or {}).get("git_sha") or "")[:7],
    }


def pct(x) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def tracked_dirs() -> set[str] | None:
    """Result directories whose summary.json is in git (ignored or not-yet-added ones would make dead links for everyone else)."""
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "results"], capture_output=True, text=True, timeout=10, check=True).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    return {p.split("/")[1] for p in out.splitlines() if p.endswith("/summary.json")}


def main() -> int:
    tracked = tracked_dirs()
    rows = [r for d in sorted(RESULTS.iterdir()) if d.is_dir() and (tracked is None or d.name in tracked) and (r := row(d))]
    lines = [
        "# results/",
        "",
        "Committed result directories (runs whose output is ignored, e.g. a mislabelled one, are left out): `report.md`, `summary.json`, `meta.json` for each run of `miniagent-eval run`. Raw trajectories and "
        "`runs.jsonl` stay local (they contain third-party model output, see `.gitignore`). This index is generated by "
        "`python scripts/index_results.py`; the experiment behind a row is described by the config's `hypothesis` field "
        "(`configs/<config>.json`) and, for the written-up ones, in `docs/ablations.md`, `docs/failure_cases.md` and `docs/next_phase_plan.md`.",
        "",
        f"{len(rows)} directories.",
        "",
        "| directory | date | config | model | split | tasks | runs | pass rate (95% CI) | mean steps | commit |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        ci = f" ({pct(r['lo'])}–{pct(r['hi'])})" if r["lo"] is not None else ""
        runs = f"{r['runs']}" + (f" (+{r['api_excluded']} API failures excluded)" if r["api_excluded"] else "")
        steps = "–" if r["steps"] is None else f"{r['steps']:.1f}"
        lines.append(f"| [`{r['dir']}`]({r['dir']}/report.md) | {r['date']} | `{r['config']}` | {r['model']} | {r['split']} | {r['tasks']} | "
                     f"{runs} | {pct(r['pass'])}{ci} | {steps} | {r['git'] or '–'} |")
    out = RESULTS / "README.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
